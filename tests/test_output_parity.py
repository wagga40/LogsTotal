"""Frozen pre-refactor outputs: intentional legacy differences must stay visible.

The expected file was captured from eda3e7a5 before the mapping refactor. It is
deliberately not regenerated by tests. Any result change needs an explicit review.
"""

from __future__ import annotations

import copy
import json
from dataclasses import asdict
from pathlib import Path
from types import SimpleNamespace

import pytest

from app.analytics import _compute_analytics_data
from app.intel.event_markers import MarkerAccumulator, build_index
from app.intel.event_timeline import build_key_events, parse_single_output_file
from app.intel.lineage import build_process_forest
from app.intel.tactics import _build_findings_index
from app.rule_attribution import authors_from_rule_text
from app.tools.registry import get_adapter

FIXTURES = Path(__file__).parent / "fixtures" / "output_parity"
CASES = json.loads((FIXTURES / "inputs.json").read_text())
EXPECTED = json.loads((FIXTURES / "expected.json").read_text()) if (FIXTURES / "expected.json").exists() else {}


def capture_case(case: dict, directory: Path, *, compressed: bool = False) -> dict:
    directory.mkdir(parents=True, exist_ok=True)
    rules = directory / "rules"
    rules.mkdir()
    for rid in ("r1", "r2", "r3"):
        (rules / f"{rid}.yml").write_text(f"title: Fixture {rid}\nid: {rid}\nauthor: Fixture Analyst\nlevel: high\n")
    adapter = get_adapter(case["tool"], {"rules_path": str(rules), "max_finding_details": case.get("cap", 1)})
    raw = copy.deepcopy(case["records"])
    findings = adapter.normalize(raw)
    assert raw == case["records"], "normalizing must not alter source evidence"
    output = directory / f"fixture_{case['tool']}.json"
    if case["tool"] in {"zircolite", "chopchopgo"}:
        payload = json.dumps(case["records"])
    else:
        payload = "\n".join(json.dumps(record) for record in case["records"])
    output.write_text(payload)
    if compressed:
        # What a finished job leaves on disk: every reader below must see the same evidence.
        from app.tools.output_files import compress_output_file

        compress_output_file(output)
        output = output.with_name(output.name + ".zst")
        assert output.is_file() and not output.with_suffix("").exists()
    models = [SimpleNamespace(**{**asdict(f), "tags": json.dumps(f.tags), "details": json.dumps(f.details), "id": i + 100}) for i, f in enumerate(findings)]
    job = SimpleNamespace(id=1, task_results=[SimpleNamespace(tool_name=case["tool"], findings=models)])
    meta = {}
    rt, tt, _ = _build_findings_index(job, rule_meta=meta)
    markers = MarkerAccumulator()
    buckets, events = parse_single_output_file(output, rt, tt, rule_meta=meta, markers=markers)
    analytics = _compute_analytics_data(job, job_dir=directory)
    analytics["relationships"] = sorted([[list(key), count] for key, count in analytics["relationships"].items()])
    analytics["relationship_evidence"] = sorted([[list(key), value] for key, value in analytics["relationship_evidence"].items()])
    matches = []
    reader_error = None
    try:
        for match in adapter.iter_raw_matches(output):
            matches.append({key: getattr(match, key) for key in ("event", "rule_name", "rule_id", "severity", "tags", "timestamp")})
    except (TypeError, ValueError, AttributeError) as exc:
        reader_error = type(exc).__name__
    key_events = build_key_events([dict(asdict(f), events=f.details, finding_id=i + 100, job_id=1) for i, f in enumerate(findings)])
    from app.tools.output_files import open_output

    with open_output(output) as stream:
        assert stream.read().decode() == payload, "readers must retain native output bytes"
    result = {
        "findings": [asdict(f) for f in findings],
        "matches": matches,
        "reader_error": reader_error,
        "buckets": buckets,
        "markers": build_index(markers),
        "analytics": analytics,
        "processes": build_process_forest(events),
        "key_events": key_events,
        "authors": [authors_from_rule_text(f.rule_content) for f in findings],
    }
    return json.loads(json.dumps(result))


@pytest.mark.parametrize("name", list(CASES))
def test_existing_tool_results_are_identical(name, tmp_path):
    assert capture_case(CASES[name], tmp_path / name) == EXPECTED[name]


@pytest.mark.parametrize("name", list(CASES))
def test_compressed_outputs_read_identically(name, tmp_path):
    """A finished job's outputs are `<name>.zst`. If any reader stopped recognising them,
    has_raw_output() would turn false and _cache_analytics would silently write no
    analytics, markers or entities for every new job — so every reader is checked against
    the same recorded results as the plain files."""
    assert capture_case(CASES[name], tmp_path / name, compressed=True) == EXPECTED[name]


@pytest.mark.parametrize(
    "name,total,groups,severity",
    [
        ("zircolite_windows", 10, 3, {"high": 10}),
        ("hayabusa_collisions", 3, 2, {"high": 2, "medium": 1}),
        ("chainsaw_wrapped", 3, 2, {"high": 3}),
        ("chopchopgo_syslog", 3, 2, {"high": 2, "informational": 1}),
        ("rsigma_windows", 4, 3, {"high": 3, "critical": 1}),
    ],
)
async def test_persisted_totals_and_export_retain_reference_results(name, total, groups, severity, async_db, test_client, tmp_path):
    from app.job_results import rollup_job_counts
    from app.models import AnalysisJob, LogFile, LogType, TaskResult, TaskStatus, WorkflowDef
    from app.tools.base import ToolOutput
    from app.workers.tasks import _persist_tool_result

    case = CASES[name]
    rules = tmp_path / "rules"
    rules.mkdir()
    for rid in ("r1", "r2", "r3"):
        (rules / f"{rid}.yml").write_text(f"title: Fixture {rid}\nid: {rid}\nauthor: Fixture Analyst\nlevel: high\n")
    workflow = WorkflowDef(name="Parity", tasks_yaml="tasks: []", log_types='["evtx"]')
    source = LogFile(original_filename="fixture.evtx", stored_filename="fixture.evtx", sha256="a" * 64, size_bytes=1, log_type=LogType.EVTX)
    async_db.add_all([workflow, source])
    await async_db.flush()
    job = AnalysisJob(file_id=source.id, workflow_id=workflow.id)
    async_db.add(job)
    await async_db.flush()
    task = TaskResult(job_id=job.id, tool_name=case["tool"], status=TaskStatus.RUNNING)
    async_db.add(task)
    await async_db.flush()
    adapter = get_adapter(case["tool"], {"rules_path": str(rules), "max_finding_details": 1})
    result = ToolOutput(success=True, findings=adapter.normalize(copy.deepcopy(case["records"])))
    await async_db.run_sync(lambda db: _persist_tool_result(db, task.id, result))
    await async_db.run_sync(lambda db: rollup_job_counts(db, job))
    await async_db.commit()
    assert job.total_findings == total
    assert task.findings_count == groups
    assert job.score_ratio == "1/1"
    assert {level: count for level, count in json.loads(job.severity_summary).items() if count} == severity

    response = await test_client.get(f"/jobs/{job.id}/findings.json")
    assert response.status_code == 200
    expected = []
    for finding, author in zip(EXPECTED[name]["findings"], EXPECTED[name]["authors"], strict=True):
        expected.append({key: value for key, value in finding.items() if key != "rule_content"} | {"tool": case["tool"], "rule_signature": None, "rule_author": author})
    assert response.json() == expected
